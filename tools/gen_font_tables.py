"""Generate site/static/js/font-tables.js: TCVN3 (ABC) and VNI-Windows -> Unicode.

Source of truth: the TCVN3 and VNI-WIN tables in Unikey's ukengine/data.cpp (all three tables list the
same 213 characters in the same order; the last 27 entries are Windows-1252 symbols, not letters).
Text that was typed in an old font and pasted today arrives as Windows-1252 characters, so the keys
here are the cp1252 *characters* a TCVN3/VNI byte turns into.

    python tools/gen_font_tables.py path/to/ukengine/data.cpp
"""
import json, re, sys
from pathlib import Path

LETTERS = 213 - 27            # entries before the Western-symbols section

def cp1252_char(b: int) -> str:
    try:
        return bytes([b]).decode("cp1252")
    except UnicodeDecodeError:            # 0x81 0x8D 0x8F 0x90 0x9D are undefined in cp1252
        return chr(b)

def section(src: str, start: str, end: str) -> str:
    i = src.index(start); j = src.index(end, i)
    return src[i + len(start):j]

def tokens(block: str):
    block = re.sub(r"//[^\n]*", "", block)          # drop comments (they contain quotes like a^)
    out = []
    for m in re.finditer(r"'(\\.|[^'])'|0x[0-9A-Fa-f]+", block):
        t = m.group(0)
        if t.startswith("0x"):
            out.append(int(t, 16))
        else:
            ch = m.group(1)
            out.append(ord(ch[1]) if ch.startswith("\\") else ord(ch))
    return out

def main(path):
    src = Path(path).read_bytes().decode("latin-1")
    uni = tokens(section(src, "UnicodeChar UnicodeTable[TOTAL_VNCHARS] =", "};"))
    tcvn = tokens(section(src, "// TCVN3", "//VPS"))
    vni = tokens(section(src, "//VNI-WIN", "//BKHCM2"))
    assert len(uni) >= LETTERS and len(tcvn) >= LETTERS and len(vni) >= LETTERS, (len(uni), len(tcvn), len(vni))
    tcvn_map, vni_map = {}, {}
    for i in range(LETTERS):
        u = chr(uni[i])
        b = tcvn[i]
        # TCVN3 dùng chung một mã cho chữ hoa và chữ thường có dấu (chữ hoa nằm ở font .VnTimeH): giữ chữ thường
        if b and (cp1252_char(b) not in tcvn_map or u.islower()):
            tcvn_map[cp1252_char(b)] = u
        w = vni[i]
        lo, hi = w & 0xFF, w >> 8
        key = cp1252_char(lo) + (cp1252_char(hi) if hi else "")
        if key != u:
            vni_map[key] = u
    tcvn_map = {k: v for k, v in tcvn_map.items() if k != v}   # ký tự trùng chính nó thì khỏi ghi
    out = Path(__file__).resolve().parent.parent / "site/static/js/font-tables.js"
    out.write_text(
        "// Generated by tools/gen_font_tables.py from the TCVN3 (ABC) and VNI-Windows code tables.\n"
        "// Keys: the Windows-1252 characters an old-font byte (or VNI byte pair) shows up as when pasted.\n"
        "(function (root) {\n"
        f"  var T = {{ TCVN3: {json.dumps(tcvn_map, ensure_ascii=False)},\n"
        f"    VNI: {json.dumps(vni_map, ensure_ascii=False)} }};\n"
        "  if (typeof module === 'object' && module.exports) module.exports = T; else root.FONT_TABLES = T;\n"
        "})(this);\n", encoding="utf-8")
    print(f"TCVN3: {len(tcvn_map)} chars, VNI: {len(vni_map)} sequences -> {out}")

if __name__ == "__main__":
    main(sys.argv[1])
